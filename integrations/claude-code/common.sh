# Общее для хуков: где лежит житель машины. Адреса Сёмы и токена здесь
# больше нет — хук ходит к жителю машины, а тот держит опознанный провод
# и сам знает, куда звонить. Секрета в настройках агента разработки не
# остаётся ни одного.
SEMAAGENT="${SEMA_AGENT_BIN:-$(command -v semaagent 2>/dev/null)}"
[ -n "$SEMAAGENT" ] || SEMAAGENT="$HOME/go/bin/semaagent"
# нет жителя машины — молчим: сессия агента разработки не должна падать
# из-за памяти
[ -x "$SEMAAGENT" ] || exit 0
